"""Postcapture-only descriptive audit; never imported by a native producer."""

import hashlib
import json
import statistics
from collections import Counter, defaultdict
from fractions import Fraction
from pathlib import Path

from .native_task import evaluate


def main():
    root = Path(__file__).resolve().parent
    capture = root / "evidence/native-v6.jsonl"
    metadata = root / "evidence/native-v6.metadata.json"
    labels = root / "native-golds-v5.json"
    rows = [json.loads(line) for line in capture.read_text().splitlines()]
    meta = json.loads(metadata.read_text())
    inputs = json.loads((root / "native-inputs-v5.json").read_text())
    answers = json.loads(labels.read_text())["answers"]
    expected = {
        (r["id"], rep, method)
        for r in inputs["records"]
        for rep in range(meta["config"]["replicates"])
        for method in meta["config"]["methods"]
    }
    actual = [(r["id"], r["rep"], r["method"]) for r in rows]
    if len(actual) != len(expected) or set(actual) != expected:
        raise ValueError("Incomplete or duplicate capture: preserve it, do not audit as complete")
    grouped, firsts = defaultdict(list), {}
    for row in rows:
        if row["calls"] != len(row["draws"]) or not row["first_preserved"]:
            raise ValueError("Original-call/first invariant failed")
        frame = (row["id"], row["rep"])
        first = row["draws"][0]["ids"]
        if firsts.setdefault(frame, first) != first:
            raise ValueError("First original IDs differ between same-seed methods")
        values = []
        for draw in row["draws"]:
            try:
                value = str(evaluate(draw["text"])) if draw["status"] == "COMPLETE" else "FAIL"
            except (ValueError, ZeroDivisionError, RecursionError, OverflowError):
                value = "FAIL"
            values.append(value)
        selected = row["selected"]
        gold = str(Fraction(answers[row["id"]]))
        grouped[row["method"]].append(
            dict(
                id=row["id"],
                rep=row["rep"],
                calls=row["calls"],
                forwards=row["forwards"],
                warm=row["warm"],
                cold=row["cold"],
                statuses=dict(Counter(d["status"] for d in row["draws"])),
                values=values,
                pass2=gold in (values[i] for i in selected),
                helpers_cover=gold in values,
                different_values=values[selected[0]] != values[selected[1]],
            )
        )
    methods = {}
    for method, cases in grouped.items():
        statuses = Counter()
        for case in cases:
            statuses.update(case["statuses"])
        methods[method] = dict(
            rows=len(cases),
            calls=sum(c["calls"] for c in cases),
            new_forwards=sum(c["forwards"] for c in cases),
            statuses=dict(statuses),
            pass2=sum(c["pass2"] for c in cases),
            helpers_cover=sum(c["helpers_cover"] for c in cases),
            different_values=sum(c["different_values"] for c in cases),
            warm_wall_median=statistics.median(c["warm"]["wall"] for c in cases),
            warm_cpu_median=statistics.median(c["warm"]["cpu"] for c in cases),
            cold_wall_median=statistics.median(c["cold"]["wall"] for c in cases),
            total_warm_wall=sum(c["warm"]["wall"] for c in cases),
            cases=cases,
        )
    report = dict(
        scope="COMPLETE small development pilot; descriptive only, no statistical victory",
        source_commit=meta["source_commit"],
        command=(
            ".venv-live/bin/python -m attempts.38-empirical-pool-coupling.work.native_pilot "
            "--source-commit 76f4bc1cfca0b6d4a9fe69aa602d3eb5913305b8 "
            "--output attempts/38-empirical-pool-coupling/work/evidence/native-v6.jsonl"
        ),
        sha256={
            p.name: hashlib.sha256(p.read_bytes()).hexdigest() for p in (capture, metadata, labels)
        },
        rows=len(rows),
        original_calls=sum(r["calls"] for r in rows),
        new_forwards=sum(r["forwards"] for r in rows),
        literal_first_ids_preserved=True,
        methods=methods,
        decision=(
            "Functional/cost pilot complete, NOT useful general EPIC superiority: "
            "adaptive4 saves calls versus the same-law full/early pools, but iid2 "
            "is cheaper with equal observed pass2; seed_half has higher observed "
            "pass2. Two replications/four questions do not confirm any quality "
            "or latency advantage. Preserve every failed/incomplete outcome."
        ),
    )
    (root / "evidence/native-audit-v7.json").write_text(json.dumps(report, indent=2) + "\n")
    table = [
        "# A38 v6 native pilot: complete postcapture audit (v7)",
        "",
        "Generated by `.venv/bin/python -m "
        "attempts.38-empirical-pool-coupling.work.analyze_native_v6`.",
        f"All{len(rows)} rows,{report['original_calls']} actual full calls and"
        f"{report['new_forwards']} new forwards retained; no replay credit.",
        "Literal first IDs agree across every same-seed method; no ERROR outcomes.",
        "Two replications/four input-hash-selected SVAMP questions: descriptive development ONLY.",
        "",
        "| Method | Calls | Forwards | Median warm wall (s) | Median warm CPU (s) | pass@2 /8 |",
        "|---|---:|---:|---:|---:|---:|",
    ]
    for method, values in sorted(methods.items()):
        table.append(
            f"| {method} | {values['calls']} | {values['new_forwards']} | "
            f"{values['warm_wall_median']:.3f} | {values['warm_cpu_median']:.3f} | "
            f"{values['pass2']} |"
        )
    table += [
        "",
        report["decision"],
        "",
        "Model loading is excluded/common and recorded separately. Cold costs add the full",
        "common grammar/prompt/initial-head preparation to EACH isolated request; see JSON.",
        "All necessary helpers, key work, native retries, copies and RNG restoration are timed.",
        "Golds were first read after all56 captures completed; no gold enters native code.",
        "Incomplete samples remain in every denominator and original marginal law.",
        "",
        "The written semantic-coarsening refinement is NEW and unimplemented here.",
        "Do not label these measurements as semantic-coarsening timings "
        "or independent confirmation.",
    ]
    (root / "native-audit-v7.md").write_text("\n".join(table) + "\n")
    print(json.dumps({k: v for k, v in report.items() if k != "methods"}, indent=2))


if __name__ == "__main__":
    main()
